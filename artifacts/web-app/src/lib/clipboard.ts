// Clipboard helper with explicit failure reporting. `navigator.clipboard` is
// unavailable in some contexts (http, older browsers, denied permission), so we
// fall back to a hidden textarea + execCommand. Returns true only when the text
// actually reached the clipboard — callers surface a toast either way instead of
// silently pretending the copy worked.
export async function copyTextToClipboard(text: string): Promise<boolean> {
  if (!text) return false;
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // fall through to the legacy path
  }
  try {
    const el = document.createElement("textarea");
    el.value = text;
    el.setAttribute("readonly", "");
    el.style.position = "fixed";
    el.style.opacity = "0";
    document.body.appendChild(el);
    el.select();
    const ok = document.execCommand("copy");
    document.body.removeChild(el);
    return ok;
  } catch {
    return false;
  }
}
